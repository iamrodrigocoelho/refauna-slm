"""F2 — seleção do registro de modelos (sem Ollama)."""

import pytest

from refauna_slm import models
from refauna_slm.config import ModelSpec, Settings


@pytest.fixture
def settings():
    return Settings(
        models={
            "gemma_base": ModelSpec(label="g", tag="gemma4:e2b", family="gemma", enabled=False, note="não cabe"),
            "gemma_ft": ModelSpec(label="gf", tag="hf.co/x/g:Q4_K_M", family="gemma"),
            "qwen_base": ModelSpec(label="q", tag="qwen3.5:2b", family="qwen"),
            "qwen_ft": ModelSpec(label="qf", tag="hf.co/x/q:Q4_K_M", family="qwen"),
        }
    )


def test_default_selection_skips_disabled(settings):
    assert list(models.select(settings, None)) == ["gemma_ft", "qwen_base", "qwen_ft"]
    assert list(models.disabled(settings, models.select(settings, None))) == ["gemma_base"]


def test_family_filter_skips_disabled(settings):
    assert list(models.select(settings, ["gemma"])) == ["gemma_ft"]
    assert list(models.select(settings, ["qwen"])) == ["qwen_base", "qwen_ft"]


def test_explicit_key_includes_disabled(settings):
    assert list(models.select(settings, ["gemma_base"])) == ["gemma_base"]


def test_unknown_key(settings):
    with pytest.raises(KeyError):
        models.select(settings, ["llama"])


def test_think_false_only_for_qwen(settings):
    assert settings.models["qwen_ft"].think is False and settings.models["gemma_ft"].think is None


def test_registry_in_settings_yaml():
    from refauna_slm.config import get_settings

    s = get_settings()
    assert set(s.models) == {"gemma_base", "gemma_ft", "qwen_base", "qwen_ft"}
    assert not s.models["gemma_base"].enabled
    assert all("tapirus" not in m.tag for m in s.models.values())


def test_normalize_tag():
    assert models.normalize_tag("gemma4") == "gemma4:latest"
    assert models.normalize_tag("hf.co/Refauna/x-GGUF:Q4_K_M") == "hf.co/Refauna/x-GGUF:Q4_K_M"


ORIGINAL_MODELFILE = """# Modelfile generated by "ollama show"
FROM /home/u/.ollama/models/blobs/sha256-texto
FROM /home/u/.ollama/models/blobs/sha256-projetor
TEMPLATE "{{ if .System }}<bos><|turn>system
{{ .System }}<turn|>
{{ end }}<|turn>model
"
PARAMETER stop <bos>
PARAMETER stop <|turn>
"""


def test_text_only_modelfile_drops_projector():
    mf = models.text_only_modelfile(ORIGINAL_MODELFILE)
    assert "sha256-texto" in mf and "sha256-projetor" not in mf
    assert "<bos><|turn>system\n{{ .System }}<turn|>" in mf
    assert mf.count("PARAMETER stop") == 2 and "RENDERER" not in mf and "PARSER" not in mf


def test_text_only_modelfile_requires_from():
    with pytest.raises(ValueError):
        models.text_only_modelfile("PARAMETER stop x")


def test_gemma_ft_is_text_only_variant():
    from refauna_slm.config import get_settings

    m = get_settings().models["gemma_ft"]
    assert m.text_only and m.source.startswith("hf.co/") and m.tag != m.source
